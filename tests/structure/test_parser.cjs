"use strict";
const assert = require("node:assert/strict");
const { StructureDocument } = require("../../src/chemistry_agent/web/structure/parser.js");
const xyz = '2\nProperties=REF_forces:R:3:species:S:1:pos:R:3 Lattice="2 0 0 0.3 3 0 0 0 4" pbc="T T F" REF_energy=-4.2\n0.1 0.2 0.3 C 0 1 2\n0.4 0.5 0.6 O 1 2 3\n1\nplain\nH 0 0 0\n';
let doc = new StructureDocument("test.extxyz", xyz);
assert.equal(doc.count, 2);
assert.deepEqual(doc.frame(0).cell, [[2,0,0],[.3,3,0],[0,0,4]]);
assert.deepEqual(doc.frame(0).pbc, [true,true,false]);
assert.equal(doc.frame(1).atoms.length, 1);
assert.equal(doc.serialize(), xyz);
doc.updateAtom(0, 1, [1.5, 2.5, 3.5]);
assert.equal(doc.frame(0).atoms[1].x, 1.5);
assert.ok(doc.serialize().includes('0.4 0.5 0.6 O 1.5000000000'));
assert.ok(doc.serialize().endsWith('1\nplain\nH 0 0 0\n'));
assert.ok(doc.serialize().includes('REF_energy=-4.2'));
assert.throws(() => doc.updateAtom(0, 1, ["", 0, 0]));
assert.throws(() => doc.replaceFrame(0, '2\n\nH 0 0 0\n'));
doc = doc.replaceFrame(0, '1\nnew frame\nCu 0 0 0\n');
assert.equal(doc.count, 2);
assert.equal(doc.frame(0).atoms[0].elem, "Cu");
assert.equal(new StructureDocument("a.xyz", xyz.replaceAll("\n", "\r\n")).serialize(), xyz.replaceAll("\n", "\r\n"));
const poscar = "CuO\n2\n1 0 0\n0.2 1 0\n0 0 1\nCu O\n1 1\nSelective dynamics\nDirect\n0 0 0 F F F\n0.5 0.5 0.5 T T T\n";
doc = new StructureDocument("sample.poscar", poscar);
assert.deepEqual(doc.frame(0).atoms[1], {elem:"O",x:1.2,y:1,z:1,serial:2});
assert.deepEqual(new StructureDocument("POSCAR", poscar.replace("\n2\n", "\n-8\n")).frame(0).cell, [[2,0,0],[.4,2,0],[0,0,2]]);
assert.equal(doc.serialize(), poscar);
const xdatcar = poscar.replace("Selective dynamics\nDirect", "Direct configuration= 1") + "Direct configuration= 2\n0 0 0\n0.4 0.5 0.5\n";
assert.equal(new StructureDocument("sample.xdatcar", xdatcar).count, 2);
assert.throws(() => new StructureDocument("a.xyz", "2\n\nH 0 0 0\n"));
assert.throws(() => new StructureDocument("a.xyz", "1\n\nH NaN 0 0\n").frame(0));
console.log("Parser: reordered properties, variable atom counts, cell/PBC, lossless edits, CRLF, POSCAR, XDATCAR and invalid input passed.");
const {ProgressiveXYZDocument} = require('../../src/chemistry_agent/web/structure/parser.js');
const progressive = new ProgressiveXYZDocument('stream.extxyz');
const firstChunk = '1\r\nfirst\r\nH 0 0 0\r\n';
const secondChunk = '\r\n2\r\nsecond\r\nO 1 2 3\r\nH 4 5 6';
progressive.append(firstChunk);
assert.equal(progressive.count, 1);
assert.equal(progressive.frame(0).atoms[0].elem, 'H');
progressive.append(secondChunk);
assert.equal(progressive.count, 2);
assert.equal(progressive.frame(1).atoms.length, 2);
assert.equal(progressive.frame(1).atoms[0].z, 3);
assert.equal(progressive.serialize(), firstChunk + secondChunk);
assert.equal(progressive.frameText(0), firstChunk.trimEnd());
assert.equal(progressive.updateAtom, undefined);
console.log('Progressive parser: append, random frame access, read-only preview and exact raw text passed.');
