const assert=require('node:assert/strict');
global.StructureParser=require('../../src/chemistry_agent/web/structure/parser.js');
const {resolve}=require('../../src/chemistry_agent/web/structure/lammps-metadata.js');
const file=text=>({name:'system.data',text});
const data='LAMMPS data file, units = metal\n\n2 atom types\n\nMasses\n\n1 63.546\n2 15.999\n\nAtoms # atomic\n';
let result=resolve([file(data)],['1','2']);
assert.deepEqual(result.mapping,{'1':'Cu','2':'O'});
assert.equal(result.atomStyle,'atomic');assert.equal(result.units,'metal');
assert.ok(result.warnings.some(text=>text.includes('质量推断')));
result=resolve([file('2 atom types\nAtom Type Labels\n1 Copper\n2 Oxygen\nMasses\nCopper 63.546 # Cu\nOxygen 15.999 # element=O')],['Copper','Oxygen']);
assert.equal(result.mapping.Copper,'Cu');assert.equal(result.mapping.Oxygen,'O');
result=resolve([file('units real\nlabelmap atom 1 Cu 2 O\nboundary p f s\natom_style full')],['1','2']);
assert.deepEqual(result.pbc,[true,false,false]);assert.equal(result.atomStyle,'full');
result=resolve([file('pair_coeff * * model.pt Cu O\n'),file('2 atom types')],['1','2']);
assert.equal(result.mapping['1'],'Cu');
assert.throws(()=>resolve([file('labelmap atom 1 C1')],['1']),/无法识别/);
assert.throws(()=>resolve([file('mass 1 1000')],['1']),/无法识别/);
assert.throws(()=>resolve([file('mass 1 2.014')],['1']),/无法识别/);
assert.throws(()=>resolve([file('labelmap atom 1 Cu'),file('labelmap atom 1 O')],['1']),/冲突/);
assert.throws(()=>resolve([file('mass 1 63.546'),file('mass 1 15.999')],['1']),/冲突/);
assert.throws(()=>resolve([file('units metal'),file('units real')]),/冲突/);
assert.throws(()=>resolve([file('units si\nmass 1 1.67e-27')]),/units si/);
assert.throws(()=>resolve([file('include /tmp/input\nshell echo nope')],['1']),/无法识别/);
console.log('LAMMPS metadata: labels, masses, commands, conflicts and unresolved types passed.');
