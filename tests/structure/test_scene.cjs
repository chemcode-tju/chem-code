const assert=require('node:assert/strict');
global.StructureSelection=require('../../src/chemistry_agent/web/structure/selection.js');
global.StructureGeometry=require('../../src/chemistry_agent/web/structure/geometry.js');
const Scene=require('../../src/chemistry_agent/web/structure/scene.js');
const reference={atoms:[{elem:'H',id:1,x:1,y:0,z:0},{elem:'O',id:2,x:5,y:0,z:0}],cell:[[10,0,0],[0,10,0],[0,0,10]],pbc:[true,true,true]};
const next={...reference,atoms:[{...reference.atoms[1],x:16},{...reference.atoms[0],x:3}]};
const display=new StructureSelection.DisplayState();display.apply(reference,[0],{style:'stick',color:'#ff0000',palette:'custom'});
const settings=Scene.settings(reference,{display,wrap:true,scale:1,drift:{referenceFrame:reference,indices:[0]}});
display.apply(reference,[0],{style:'sphere'});display.hiddenElements.add('H');
const preview=Scene.build(reference,settings),exported=Scene.build(next,settings);
assert.equal(preview.options.display.resolve(reference.atoms[0],0,{}).style,'stick');
assert.equal(exported.options.display.resolve(next.atoms[1],1,{}).style,'stick');
assert.equal(exported.options.display.resolve(next.atoms[1],1,{}).visible,true);
assert.equal(exported.frame.atoms[1].x,1);assert(Math.abs(exported.frame.atoms[0].x-4)<1e-9);
assert.equal(next.atoms[0].x,16);assert.equal(reference.atoms[0].x,1);
assert.equal(preview.options.lighting,exported.options.lighting);
assert.deepEqual(Scene.build(reference,settings),preview);
assert.throws(()=>Scene.build({...next,atoms:[{elem:'C',x:0,y:0,z:0}]},settings),/对应/);
console.log('Shared scene: frozen display settings, ID remapping, drift then wrap, identical lighting and unchanged input coordinates passed.');
